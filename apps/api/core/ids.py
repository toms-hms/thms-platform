"""CUID2 identifier generation.

Primary keys across the schema are CUID2 strings generated by the application,
not by the database — every insert must supply one. This mirrors the format the
Express API produced with `@paralleldrive/cuid2`: 24 characters, a leading
letter followed by base36 characters.
"""

import os
import secrets
import time
from hashlib import sha3_512

DEFAULT_LENGTH = 24
BASE36_DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"
_ALPHABET = "abcdefghijklmnopqrstuvwxyz"
_counter = secrets.randbelow(2057)
_fingerprint = f"{os.getpid()}{os.urandom(8).hex()}"


def _to_base36(value: int) -> str:
    """Returns the integer encoded in base36 using lowercase digits."""
    if value == 0:
        return "0"
    out: list[str] = []
    while value:
        value, remainder = divmod(value, 36)
        out.append(BASE36_DIGITS[remainder])
    return "".join(reversed(out))


def create_id(length: int = DEFAULT_LENGTH) -> str:
    """Returns a new collision-resistant CUID2 of the given length, always starting with a letter."""
    global _counter
    _counter += 1
    first_letter = secrets.choice(_ALPHABET)
    salt = secrets.token_hex(32)
    block = f"{_to_base36(time.time_ns())}{salt}{_to_base36(_counter)}{_fingerprint}"
    digest = _to_base36(int.from_bytes(sha3_512(block.encode()).digest(), "big"))
    return (first_letter + digest)[:length]
